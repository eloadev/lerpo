--  Pega TODO este archivo en Supabase → SQL Editor → Run.
--  Se puede correr una sola vez en un proyecto nuevo.
--
--  Seguridad:
--   • Las contraseñas las maneja Supabase Auth (hash bcrypt). Nunca se
--     guardan en estas tablas ni pasan por tu código.
--   • Row Level Security (RLS) en TODAS las tablas: la base de datos
--     misma decide quién ve qué, aunque alguien manipule el JavaScript.
--   • Los links de invitación se guardan como hash SHA-256; el link
--     real solo se muestra una vez al crearlo.
-- =====================================================================

-- ---------- Tablas -------------------------------------------------------

create table public.profiles (
  id           uuid primary key references auth.users (id) on delete cascade,
  email        text,
  full_name    text not null default '' check (char_length(full_name) <= 80),
  avatar_color text not null default '#6d5bd0' check (avatar_color ~* '^#[0-9a-f]{6}$'),
  is_admin     boolean not null default false,
  created_at   timestamptz not null default now()
);

create table public.areas (
  id       smallint generated by default as identity primary key,
  name     text not null check (char_length(name) between 1 and 40),
  color    text not null check (color ~* '^#[0-9a-f]{6}$'),
  position smallint not null default 0
);

create table public.projects (
  id          uuid primary key default gen_random_uuid(),
  name        text not null check (char_length(name) between 1 and 80),
  description text not null default '' check (char_length(description) <= 2000),
  image_url   text check (image_url is null or image_url ~* '^https://'),
  area_ids    smallint[] not null default '{}',
  status      text not null default 'active' check (status in ('active', 'archived')),
  created_by  uuid default auth.uid() references public.profiles (id) on delete set null,
  created_at  timestamptz not null default now()
);

create table public.project_members (
  project_id uuid not null references public.projects (id) on delete cascade,
  user_id    uuid not null references public.profiles (id) on delete cascade,
  role       text not null default 'member' check (role in ('admin', 'member', 'viewer')),
  joined_at  timestamptz not null default now(),
  primary key (project_id, user_id)
);
create index on public.project_members (user_id);

create table public.sprints (
  id         uuid primary key default gen_random_uuid(),
  project_id uuid not null references public.projects (id) on delete cascade,
  name       text not null check (char_length(name) between 1 and 80),
  goal       text not null default '' check (char_length(goal) <= 500),
  start_date date,
  end_date   date,
  position   int not null default 0,
  created_at timestamptz not null default now(),
  unique (id, project_id),
  check (start_date is null or end_date is null or end_date >= start_date)
);
create index on public.sprints (project_id);

create table public.tasks (
  id          uuid primary key default gen_random_uuid(),
  project_id  uuid not null references public.projects (id) on delete cascade,
  sprint_id   uuid,
  title       text not null check (char_length(title) between 1 and 200),
  description text not null default '' check (char_length(description) <= 10000),
  status      text not null default 'upcoming' check (status in ('upcoming', 'in_progress', 'done')),
  area_id     smallint references public.areas (id) on delete set null,
  deliverable text not null default '' check (char_length(deliverable) <= 1000),
  due_date    date,
  position    double precision not null default 0,
  created_by  uuid default auth.uid() references public.profiles (id) on delete set null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  -- una tarea solo puede estar en un sprint de SU proyecto
  foreign key (sprint_id, project_id) references public.sprints (id, project_id) on delete set null (sprint_id)
);
create index on public.tasks (project_id, sprint_id);

create table public.task_assignees (
  task_id uuid not null references public.tasks (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
  primary key (task_id, user_id)
);

create table public.checklist_items (
  id         uuid primary key default gen_random_uuid(),
  task_id    uuid not null references public.tasks (id) on delete cascade,
  text       text not null check (char_length(text) between 1 and 300),
  done       boolean not null default false,
  position   double precision not null default 0,
  created_at timestamptz not null default now()
);
create index on public.checklist_items (task_id);

create table public.comments (
  id         uuid primary key default gen_random_uuid(),
  task_id    uuid not null references public.tasks (id) on delete cascade,
  user_id    uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  body       text not null check (char_length(body) between 1 and 4000),
  created_at timestamptz not null default now()
);
create index on public.comments (task_id);

create table public.invitations (
  id         uuid primary key default gen_random_uuid(),
  project_id uuid not null references public.projects (id) on delete cascade,
  token_hash text not null unique,
  role       text not null default 'member' check (role in ('admin', 'member', 'viewer')),
  note       text not null default '' check (char_length(note) <= 80),
  created_by uuid default auth.uid() references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  max_uses   int check (max_uses is null or max_uses > 0),
  uses       int not null default 0,
  revoked    boolean not null default false
);
create index on public.invitations (project_id);

