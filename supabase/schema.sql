-- ---------- Funciones auxiliares de permisos ----------------------------
-- security definer + search_path fijo: se ejecutan con permisos del dueño
-- para poder consultar membresías sin recursión de RLS.

create function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((select is_admin from public.profiles where id = auth.uid()), false);
$$;

create function public.project_role(p uuid) returns text
language sql stable security definer set search_path = public as $$
  select role from public.project_members where project_id = p and user_id = auth.uid();
$$;

create function public.is_member(p uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select public.is_admin()
      or exists (select 1 from public.project_members where project_id = p and user_id = auth.uid());
$$;

create function public.can_edit(p uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select public.is_admin() or coalesce(public.project_role(p) in ('admin', 'member'), false);
$$;

create function public.can_manage(p uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select public.is_admin() or coalesce(public.project_role(p) = 'admin', false);
$$;

create function public.task_project(t uuid) returns uuid
language sql stable security definer set search_path = public as $$
  select project_id from public.tasks where id = t;
$$;

create function public.user_in_project(p uuid, u uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.project_members where project_id = p and user_id = u);
$$;

create function public.shares_project(u uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.project_members a
    join public.project_members b on a.project_id = b.project_id
    where a.user_id = auth.uid() and b.user_id = u
  );
$$;

-- ---------- Triggers -----------------------------------------------------

-- Crea el perfil cuando alguien se registra
create function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, email, full_name)
  values (new.id, new.email,
          left(coalesce(nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''), split_part(new.email, '@', 1)), 80));
  return new;
end $$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Quien crea un proyecto queda como admin de ese proyecto
create function public.add_project_owner() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.created_by is not null then
    insert into public.project_members (project_id, user_id, role)
    values (new.id, new.created_by, 'admin')
    on conflict do nothing;
  end if;
  return new;
end $$;

create trigger on_project_created
  after insert on public.projects
  for each row execute function public.add_project_owner();

-- updated_at automático en tareas
create function public.touch_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end $$;

create trigger tasks_touch before update on public.tasks
  for each row execute function public.touch_updated_at();

-- Si cambia el checklist o los asignados, "toca" la tarea (para tiempo real)
create function public.touch_parent_task() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  update public.tasks set updated_at = now()
  where id = coalesce(new.task_id, old.task_id);
  return null;
end $$;

create trigger checklist_touch after insert or update or delete on public.checklist_items
  for each row execute function public.touch_parent_task();
create trigger assignees_touch after insert or delete on public.task_assignees
  for each row execute function public.touch_parent_task();

-- No se puede degradar ni sacar al último admin de un proyecto
create function public.keep_one_admin() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if old.role = 'admin'
     and (tg_op = 'DELETE' or new.role <> 'admin')
     and exists (select 1 from public.projects where id = old.project_id)
     and not exists (select 1 from public.project_members
                     where project_id = old.project_id and role = 'admin' and user_id <> old.user_id) then
    raise exception 'El proyecto necesita al menos un admin' using errcode = 'P0001';
  end if;
  return coalesce(new, old);
end $$;

create trigger members_keep_admin before update or delete on public.project_members
  for each row execute function public.keep_one_admin();

