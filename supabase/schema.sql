-- Dashboard: todos los proyectos con su % de avance.
-- Solo responde a gente que ya pertenece al equipo (admin o miembro de algo).
create function public.dashboard_projects()
returns table (
  id uuid, name text, description text, image_url text, area_ids smallint[],
  status text, total_tasks int, done_tasks int, progress int,
  member_count int, is_member boolean, my_role text, created_at timestamptz
)
language sql stable security definer set search_path = public as $$
  select p.id, p.name, p.description, p.image_url, p.area_ids, p.status,
         coalesce(t.total, 0)::int,
         coalesce(t.done, 0)::int,
         case when coalesce(t.total, 0) = 0 then 0
              else round(100.0 * t.done / t.total)::int end,
         (select count(*) from public.project_members m where m.project_id = p.id)::int,
         public.is_member(p.id),
         coalesce(public.project_role(p.id), case when public.is_admin() then 'admin' end),
         p.created_at
  from public.projects p
  left join lateral (
    select count(*) as total, count(*) filter (where x.status = 'done') as done
    from public.tasks x where x.project_id = p.id
  ) t on true
  where public.is_admin()
     or exists (select 1 from public.project_members m where m.user_id = auth.uid())
  order by p.created_at desc;
$$;

-- Crea un link de invitación. Devuelve el token UNA sola vez.
create function public.create_invite(
  p_project uuid, p_role text default 'member', p_days int default 7,
  p_max_uses int default null, p_note text default ''
) returns text
language plpgsql volatile security definer set search_path = public as $$
declare
  v_token text;
begin
  if auth.uid() is null or not public.can_manage(p_project) then
    raise exception 'No tienes permiso para invitar a este proyecto' using errcode = '42501';
  end if;
  if p_role not in ('admin', 'member', 'viewer') then
    raise exception 'Rol inválido' using errcode = '22023';
  end if;
  if p_days is null or p_days < 1 or p_days > 90 then
    raise exception 'La expiración debe ser de 1 a 90 días' using errcode = '22023';
  end if;
  if p_max_uses is not null and (p_max_uses < 1 or p_max_uses > 100) then
    raise exception 'Usos máximos: de 1 a 100' using errcode = '22023';
  end if;

  -- 2 UUID v4 = 244 bits aleatorios → imposible de adivinar
  v_token := replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', '');

  insert into public.invitations (project_id, token_hash, role, expires_at, max_uses, note)
  values (p_project, encode(sha256(convert_to(v_token, 'UTF8')), 'hex'), p_role,
          now() + make_interval(days => p_days), p_max_uses, left(coalesce(p_note, ''), 80));

  return v_token;
end $$;

-- Vista previa: a qué proyecto te invitan (sin unirte todavía)
create function public.invite_preview(p_token text)
returns table (project_id uuid, project_name text, role text, already_member boolean)
language sql stable security definer set search_path = public as $$
  select i.project_id, p.name, i.role, public.user_in_project(i.project_id, auth.uid())
  from public.invitations i
  join public.projects p on p.id = i.project_id
  where auth.uid() is not null
    and i.token_hash = encode(sha256(convert_to(coalesce(p_token, ''), 'UTF8')), 'hex')
    and not i.revoked
    and i.expires_at > now()
    and (i.max_uses is null or i.uses < i.max_uses);
$$;

-- Aceptar invitación → te vuelve miembro del proyecto
create function public.accept_invite(p_token text) returns uuid
language plpgsql volatile security definer set search_path = public as $$
declare
  v_inv public.invitations%rowtype;
  v_inserted int;
begin
  if auth.uid() is null then
    raise exception 'Inicia sesión primero' using errcode = '42501';
  end if;

  select * into v_inv from public.invitations
  where token_hash = encode(sha256(convert_to(coalesce(p_token, ''), 'UTF8')), 'hex')
  for update;

  if not found or v_inv.revoked or v_inv.expires_at <= now()
     or (v_inv.max_uses is not null and v_inv.uses >= v_inv.max_uses) then
    raise exception 'Esta invitación no es válida o ya expiró' using errcode = 'P0002';
  end if;

  insert into public.project_members (project_id, user_id, role)
  values (v_inv.project_id, auth.uid(), v_inv.role)
  on conflict do nothing;
  get diagnostics v_inserted = row_count;

  if v_inserted > 0 then
    update public.invitations set uses = uses + 1 where id = v_inv.id;
  end if;

  return v_inv.project_id;
end $$;

-- Mover tarea en el tablero (respeta RLS: corre con permisos del usuario)
create function public.reorder_tasks(p_status text, p_ids uuid[]) returns void
language sql volatile security invoker set search_path = public as $$
  update public.tasks t
     set status = p_status, position = x.ord
    from unnest(p_ids) with ordinality as x(id, ord)
   where t.id = x.id;
$$;

